-- =====================================================================
-- Level 2 Listening story bank.
--
-- 40 stories of about two minutes each, with 10 inference-first questions apiece, in the shape
-- set by The Atlas Cutover in data.sql: real migration work, named people, real numbers, a
-- judgement that turns out to be wrong, something deferred rather than solved, and a cost.
--
-- Sizing. ContentAssignmentService pins one story per attempt and excludes every story that
-- candidate has already been served, so no one ever meets the same story twice. Across 100
-- candidates taking 2 attempts a year the least-recently-served rule spreads 200 assignments
-- over these 40, so each is heard about five times in a year by different people. That is the
-- deliberate difference from Speaking, where 200 disjoint sets mean no two candidates ever
-- share: a listening story is 350 words plus 10 questions, and 200 of them could not be held
-- to this standard. Two candidates may therefore hear the same story; neither repeats their own.
--
-- Seeded behind a seed_state marker rather than a row-existence guard. data.sql guards its
-- Level 2 story on NOT EXISTS (... WHERE level = 2), which is already true in production, so
-- rows appended there would never load on a live database. Bump the key to -v2 to push a
-- revision -- and note that a revision must delete the old rows first, because a title that
-- already exists would otherwise attach its questions to the wrong story.
--
-- Question design. Item 1 is always the cause, and the plausible-but-wrong hypothesis from the
-- narrative is always an option. Somewhere in each set there is one arithmetic item (a total or
-- an interval the candidate must compute rather than recall), one that separates what was
-- DEFERRED from what was RESOLVED, one about the limit of an agreement, and a final item asking
-- which sentence best summarises the briefing. Recall-only items are kept to a minority: the
-- test is whether a candidate followed the reasoning, not whether they memorised a number.
--
-- Avoid apostrophes: these are single-quoted SQL literals.
-- =====================================================================

